@ApiTags('news')
@ApiBearerAuth()
@UseGuards(JwtAuthGuard)
@Controller('news')
export class NewsController {
  @Get() feed(@Query('okved') okved = '', @Query('status') status?: string) {
    if (okved && !/^\d{2}(\.\d{1,2}){0,2}$/.test(okved))
      throw new BadRequestException('Некорректный ОКВЭД');
    if (
      status &&
      !Object.values(ApplicationStatus).includes(status as ApplicationStatus)
    )
      throw new BadRequestException('Неизвестный статус');
    return NEWS.filter(
      (n) =>
        (!n.targetOkved || okved.startsWith(n.targetOkved)) &&
        (!n.targetStage || n.targetStage === status),
    ).sort(
      (a, b) =>
        Number(!!b.targetStage) * 10 +
        Number(!!b.targetOkved) -
        Number(!!a.targetStage) * 10 -
        Number(!!a.targetOkved),
    );
  }
  @Get(':id') article(@Param('id') id: string) {
    const n = NEWS.find((n) => n.id === id);
    if (!n) throw new NotFoundException('Статья не найдена');
    return n;
  }
}
